<div id="contexte">
  <h3 data-i18n="audion.contextTitle">Contexte</h3>

  <p>
    <span data-i18n="audion.contextP1a">Audion, une plateforme d'IA pour la publicité audio, se lance aux États-Unis avec une campagne de publicités LinkedIn ciblant les CMOs. L'appât : un livre blanc de 22 pages, le</span>
    <em>2026 US Channel Mix Report</em>
    <span data-i18n="audion.contextP1b">, sur la répartition des budgets média américains. Ma mission : concevoir la landing page où arrivent les clics, pour transformer ce trafic en leads qualifiés. Je suis intervenue uniquement sur cette page de campagne, pas sur le site officiel d'Audion.</span>
  </p>

  <p data-i18n="audion.contextP2">
    Le chef de projet me briefait. J'ai travaillé avec le SEO, le SEA et le tracking, et validé les choix avec les CMOs et les sales d'Audion.
  </p>

  <ul class="key-challenges">
    <li>
      <b data-i18n="audion.challenge1Title">Un public mobile</b>
      <span data-i18n="audion.challenge1Text">La plupart des utilisateurs de LinkedIn naviguent depuis leur téléphone : la page devait d'abord fonctionner sur mobile.</span>
    </li>
    <li>
      <b data-i18n="audion.challenge2Title">Une attention courte</b>
      <span data-i18n="audion.challenge2Text">Après un clic sur une pub, la page doit confirmer la promesse de la créa en quelques secondes.</span>
    </li>
    <li>
      <b data-i18n="audion.challenge3Title">Des décideurs très sollicités</b>
      <span data-i18n="audion.challenge3Text">Convaincre un CMO de laisser ses coordonnées, pour une marque encore peu connue aux États-Unis.</span>
    </li>
    <li>
      <b data-i18n="audion.challenge4Title">Deux objectifs</b>
      <span data-i18n="audion.challenge4Text">Obtenir des leads avant tout, et faire découvrir Audion à ceux qui arrivent sur la page.</span>
    </li>
  </ul>
</div>
 
<div id="strategie">
  <h3 data-i18n="audion.strategyTitle">Stratégie</h3>

  <div class="process-steps">
    <div class="step">
      <h4 data-i18n="audion.strategy1Title">Deux objectifs</h4>
      <p data-i18n="audion.strategy1Text">
        Obtenir des leads qualifiés grâce au formulaire, puis présenter Audion à ceux qui arrivent sur la page.
      </p>
    </div>

    <div class="step">
      <h4 data-i18n="audion.strategy2Title">Version A : conversion d'abord</h4>
      <p data-i18n="audion.strategy2Text">
        Un hero centré sur le livre blanc et le formulaire, un aperçu du contenu, de la preuve sociale, puis une présentation d'Audion.
      </p>
    </div>

    <div class="step">
      <h4 data-i18n="audion.strategy3Title">Version B : marque et conversion</h4>
      <p data-i18n="audion.strategy3Text">
        Un hero qui mêle proposition de valeur et formulaire, puis « pourquoi l'audio ? » et une présentation plus poussée d'Audion.
      </p>
    </div>
  </div>

  <!-- Conserve ici les trois images existantes : image-1, image-2 et image-3. -->

  <p data-i18n="audion.strategyConclusion">
    La page finale reprend la structure de la version A, avec une section sur les atouts de l'audio issue de la B.
  </p>
</div>
 
    <div id="decisions">
  <h3 data-i18n="audion.decisionsTitle">Décisions clés</h3>

  <ul class="key-challenges">
    <li>
      <b data-i18n="audion.decision1Title">Un formulaire à 3 champs au lieu de 5</b>
      <span data-i18n="audion.decision1Text">
        Les sales voulaient 5 champs pour récolter un maximum de données. J'ai recommandé 2 à 3 champs maximum, car chaque champ en plus fait chuter le taux de complétion, surtout sur mobile. Le formulaire final compte 3 champs : nom, rôle (annonceur, agence ou adtech) et e-mail professionnel.
      </span>
    </li>
    <li>
      <b data-i18n="audion.decision2Title">Un hero qui donne envie de télécharger</b>
      <span data-i18n="audion.decision2Text">
        Dès le premier écran : un titre centré sur le bénéfice, un visuel du rapport, la mention « 22 pages », des logos de marques pour rassurer et le formulaire.
      </span>
    </li>
    <li>
      <b data-i18n="audion.decision3Title">Une page de remerciement qui prolonge la visite</b>
      <span data-i18n="audion.decision3Text">
        Une confirmation du téléchargement, puis un appel à l'action vers Audion et trois cartes pour continuer à explorer.
      </span>
    </li>
    <li>
      <b data-i18n="audion.decision4Title">Des itérations sans test utilisateur</b>
      <span data-i18n="audion.decision4Text">
        Pas de test utilisateur sur ce projet : j'ai ajusté la page avec mon expérience des landing pages et les retours des sales et des CMOs. Les allers-retours ont porté sur le formulaire, les visuels, le titre et les textes, les icônes, les logos et les boutons.
      </span>
    </li>
  </ul>

  <!-- Conserve ici la vidéo existante. -->
</div>
 
   <div id="resultats">
  <h3 data-i18n="audion.resultsTitle">Résultats</h3>

  <p data-i18n="audion.resultsText">
    La landing est livrée en 6 semaines et en ligne : elle a servi de destination aux publicités LinkedIn. Elle arrive en bout de funnel et le trafic est resté limité, donc je n'ai pas de données de conversion fiables à partager.
  </p>

  <h4 data-i18n="audion.takeawaysTitle">Ce que j'en retiens</h4>
  <p data-i18n="audion.takeawaysText">
    Proposer deux versions rend la discussion plus concrète. Et sur le formulaire, parler en leads et en taux de complétion m'a aidée à convaincre les sales : mon passé marketing a servi.
  </p>

  <h4 data-i18n="audion.nextStepsTitle">Ce que je ferais ensuite</h4>
  <p data-i18n="audion.nextStepsText">
    Tester deux titres et deux longueurs de formulaire, et analyser les sessions mobiles pour repérer où les utilisateurs abandonnent.
  </p>

